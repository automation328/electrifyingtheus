// EPA range in miles, by model year and by variant — the figure that belongs on
// a USED car, and on a particular one.
//
// src/data/ev-catalog.ts carries one range per nameplate: the current car. That
// is right for the comparison pages, which price new cars, and wrong everywhere
// a second-hand listing appears. A 2013 Nissan LEAF was showing 303 miles, the
// figure for a 2026 LEAF; it does 75.
//
// One model year is not one figure either. The EPA rates a 2026 LYRIQ four
// times — 326 rear-drive, 319 PAWD, 303 AWD, 285 V-Series — so a card that
// said "285–326 mi" was quoting a spread no car on it achieves. Every listing
// names its trim and its drivetrain, which is usually enough to pick one row.
//
// Generated by scripts/refresh-ev-ranges.py from the EPA's own vehicle dataset
// (fueleconomy.gov/feg/epadata/vehicles.csv), every battery-electric row from
// 2011 on, grouped by the car it matches in our catalog.
//
// No imports: the marketplace's serverless function reads this too.

/** One figure, or the low and high of that year's variants. */
export type EpaRangeBand = readonly [number] | readonly [number, number];

/**
 * One EPA rating: miles, drive letter, and the words that tell it apart.
 *
 * The drive letter is "r", "f", "a" or "" — four-wheel drive counts as all-wheel
 * because listings write both as AWD. The third cell is the EPA's model text
 * with the nameplate and the drive words removed ("Model 3 Long Range AWD" →
 * "long range"), and is absent when nothing distinguishes the row.
 */
export type EpaVariant = readonly [number, string] | readonly [number, string, string];

/** What a listing knows about itself, and we can match a variant against. */
export interface ListingVariantHint {
  trim?: string;
  drivetrain?: string;
}

