/** How far a model year may be from one we hold before the figure stops being
 *  evidence about that car: a facelift moves range, a decade moves it entirely. */
const NEAREST_YEAR_TOLERANCE = 2;

/**
 * EPA range for one car in one model year.
 *
 * Returns nothing when we hold no figure close enough to the year asked for —
 * the caller then shows no range at all, which is the honest answer. Showing
 * the current car's range on a ten-year-old listing is not.
 */
export function epaRangeFor(
  catalogId: string, year?: number,
): { rangeMi?: number; rangeMaxMi?: number } {
  const byYear = EV_RANGE_BY_YEAR[catalogId];
  if (!byYear || !year) return {};

  const exact = byYear[year];
  const band = exact ?? (() => {
    let best: EpaRangeBand | undefined;
    let bestGap = Infinity;
    for (const [candidate, value] of Object.entries(byYear)) {
      const gap = Math.abs(Number(candidate) - year);
      if (gap < bestGap && gap <= NEAREST_YEAR_TOLERANCE) { best = value; bestGap = gap; }
    }
    return best;
  })();

  if (!band) return {};
  return band.length === 1
    ? { rangeMi: band[0] }
    : { rangeMi: band[0], rangeMaxMi: band[1] };
}
