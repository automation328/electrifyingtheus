/** Low and high of a set of variants. */
const bandOf = (variants: readonly EpaVariant[]): EpaRangeBand | undefined => {
  if (!variants.length) return undefined;
  const miles = variants.map((v) => v[0]);
  const lo = Math.min(...miles);
  const hi = Math.max(...miles);
  return lo === hi ? [lo] : [lo, hi];
};

/**
 * Every variant of a car in a year, collapsed to one band.
 *
 * Kept for the callers that have no listing to narrow by, and for the tests
 * that pin the dataset itself.
 */
export const EV_RANGE_BY_YEAR: Readonly<Record<string, Readonly<Record<number, EpaRangeBand>>>> =
  Object.fromEntries(
    Object.entries(EV_RANGE_VARIANTS).map(([id, byYear]) => [
      id,
      Object.fromEntries(
        Object.entries(byYear)
          .map(([year, variants]) => [Number(year), bandOf(variants)])
          .filter(([, band]) => band != null),
      ),
    ]),
  );

/** How far a model year may be from one we hold before the figure stops being
 *  evidence about that car: a facelift moves range, a decade moves it entirely. */
const NEAREST_YEAR_TOLERANCE = 2;

/** Drivetrain words, however a dealer writes them, as the EPA's drive letter. */
const DRIVE_LETTERS: Readonly<Record<string, string>> = {
  rwd: "r", rear: "r",
  fwd: "f", front: "f",
  awd: "a", all: "a", "4wd": "a", "4x4": "a", "4matic": "a", quattro: "a", xdrive: "a",
};

/** Words that appear in trims without saying which car it is. */
const NOISE = new Set([
  "4dr", "2dr", "suv", "sedan", "coupe", "hatchback", "wagon", "crossover", "truck",
  "electric", "ev", "bev", "base", "w", "pkg", "package", "with", "and", "the",
  "rwd", "fwd", "awd", "4wd", "4x4", "2wd", "4matic", "quattro", "xdrive",
]);

/**
 * Words in an EPA label that describe EQUIPMENT rather than which trim the car
 * is: the battery, the wheels, the on-board charger.
 *
 * The distinction decides what a vague trim is allowed to mean. A dealer will
 * happily leave "extended range" or "20-inch wheels" out of the trim field, so
 * those ratings have to stay in the band; a dealer does not leave out
 * "V-Series", so a listing that does not claim one is not one.
 *
 * A label made only of these words — or of nothing — is the ordinary car.
 */
const EQUIPMENT_WORDS = new Set([
  "kw", "kwh", "charger", "inch", "in", "wheel", "wheels", "alloy", "steel",
  "battery", "pack", "range", "extended", "standard", "long", "short",
  "er", "sr", "lr", "lfp", "nmc", "dual", "single", "motor", "tires",
]);

/** Whether this variant is the plain car rather than a named trim. */
const isPlainVariant = (variant: EpaVariant): boolean =>
  words(variant[2]).every((w) => EQUIPMENT_WORDS.has(w) || /^\d+$/.test(w));

const words = (text?: string): string[] =>
  (text ?? "").toLowerCase().match(/[a-z0-9]+/g) ?? [];

const driveOf = (text?: string): string | undefined => {
  for (const word of words(text)) {
    const letter = DRIVE_LETTERS[word];
    if (letter) return letter;
  }
  return undefined;
};

/**
 * The variants a listing could be, narrowed as far as its own words allow.
 *
 * Drivetrain first, because it is the one field dealers fill in reliably, then
 * trim words. A filter that would leave nothing is not applied: a car we cannot
 * place among the variants is still a car of that year, so it keeps the year's
 * whole band rather than losing its range entirely.
 */
function narrow(variants: readonly EpaVariant[], hint?: ListingVariantHint): readonly EpaVariant[] {
  let kept = variants;

  const drive = driveOf(hint?.drivetrain);
  if (drive) {
    const byDrive = kept.filter((v) => v[1] === drive);
    if (byDrive.length) kept = byDrive;
  }

  const spoken = words(hint?.trim).filter((w) => !NOISE.has(w));
  const wanted = spoken.filter((w, i) => (
    // A one-letter word only counts when it is the whole trim. Hyundai sells
    // both an IONIQ 5 N (221 miles) and an IONIQ 5 SEL with the N Line package
    // (290), and matching on that lone "n" handed the SEL the N's rating.
    (w.length > 1 || spoken.length === 1)
    // "GT-Line", "N Line" and "Sport Package" are decor sold on the ordinary
    // car and named after the fast one, so the word before "line" or "package"
    // is not a claim to be it. A Kia EV9 GT-Line does 280 miles; the GT, 260.
    && spoken[i + 1] !== "line" && spoken[i + 1] !== "package"
  ));
  if (wanted.length) {
    const scored = kept.map((v) => {
      const have = words(v[2]);
      const hit = new Set(have.filter((w) => wanted.includes(w)));
      // Ties break towards the label with least left over, so a car that says
      // "GT" takes the EV9 GT rather than the GT-Line, whose label also
      // contains "gt" but three words we were told nothing about.
      return { v, score: hit.size, spare: have.length - hit.size };
    });
    const best = Math.max(...scored.map((s) => s.score));
    if (best > 0) {
      const tightest = Math.min(...scored.filter((s) => s.score === best).map((s) => s.spare));
      return scored.filter((s) => s.score === best && s.spare === tightest).map((s) => s.v);
    }

    // Nothing matched, so this car is none of the named trims: a LYRIQ Luxury
    // is not the V-Series whose 285 miles was setting the low end.
    //
    // Only where an ordinary car exists to fall back to, though. Every BMW iX
    // the EPA rates carries a trim word — xDrive40, xDrive50, M60 — so dropping
    // the named ones once left the xDrive50 alone and quoted a 217-mile
    // xDrive40 at 307. When every variant is a named trim, the trim text told
    // us nothing and the year's whole band is the honest answer.
    const plain = kept.filter(isPlainVariant);
    if (plain.length) kept = plain;
  }

  return kept;
}

/**
 * EPA range for one car in one model year, for this listing where we can tell.
 *
 * Returns nothing when we hold no figure close enough to the year asked for —
 * the caller then shows no range at all, which is the honest answer. Showing
 * the current car's range on a ten-year-old listing is not.
 */
export function epaRangeFor(
  catalogId: string, year?: number, hint?: ListingVariantHint,
): { rangeMi?: number; rangeMaxMi?: number } {
  const byYear = EV_RANGE_VARIANTS[catalogId];
  if (!byYear || !year) return {};

  const exact = byYear[year];
  const variants = exact ?? (() => {
    let best: readonly EpaVariant[] | undefined;
    let bestGap = Infinity;
    for (const [candidate, value] of Object.entries(byYear)) {
      const gap = Math.abs(Number(candidate) - year);
      if (gap < bestGap && gap <= NEAREST_YEAR_TOLERANCE) { best = value; bestGap = gap; }
    }
    return best;
  })();

  if (!variants?.length) return {};
  const band = bandOf(narrow(variants, hint));
  if (!band) return {};
  return band.length === 1
    ? { rangeMi: band[0] }
    : { rangeMi: band[0], rangeMaxMi: band[1] };
}
