// EPA range in miles, by model year — the figure that belongs on a USED car.
//
// src/data/ev-catalog.ts carries one range per nameplate: the current car. That
// is right for the comparison pages, which price new cars, and wrong everywhere
// a second-hand listing appears. A 2013 Nissan LEAF was showing 303 miles, the
// figure for a 2026 LEAF; it does 75.
//
// Generated from the EPA's own vehicle dataset (fueleconomy.gov/feg/epadata/
