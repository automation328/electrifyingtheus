// Turns each built-in event's flyer (src/data/events.ts) into a 1200x630 JPEG
// at public/og/events/<slug>.jpg and writes og-events.ts, so a shared
// /events/<slug> link previews with that event's own flyer. The image work is
// scripts/og-flyer.py (needs Python with Pillow).
//
// The share previews come from middleware.ts, which runs on Vercel's edge and
// cannot import the bundled flyers (their file names carry a build hash).
// Re-run after adding or changing a built-in event:
//   npx vite-node scripts/make-og-events.ts
// src/lib/og-events.test.ts fails until you do.

import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { EVENTS } from "../src/data/events";

const MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];

// Start clean so a removed or renamed event leaves no orphan image behind.
rmSync("public/og/events", { recursive: true, force: true });
mkdirSync("public/og/events", { recursive: true });
const rows = [];
for (const e of EVENTS) {
  if (!e.slug || typeof e.image !== "string" || !e.image.startsWith("/src/")) continue;
  const src = e.image.split("?")[0].slice(1); // "/src/assets/x.jpg" -> "src/assets/x.jpg"
  const image = `/og/events/${e.slug}.jpg`;
  execFileSync("python", ["scripts/og-flyer.py", src, `public${image}`], { stdio: "inherit" });
  const date = `${e.year}-${String(MONTHS.indexOf(e.month) + 1).padStart(2, "0")}-${String(Number(e.day) || 0).padStart(2, "0")}`;
  rows.push({ slug: e.slug, title: e.title.trim(), date, description: e.description.slice(0, 200), image });
}

writeFileSync(
  "og-events.ts",
  `// Generated by scripts/make-og-events.ts. Do not edit by hand.
// Built-in events' share previews, read by middleware.ts. \`date\` + \`title\`
// match a database row that adopted the event (same rule as src/lib/content.ts).

export interface OgEvent { slug: string; title: string; date: string; description: string; image: string }

export const OG_EVENTS: OgEvent[] = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(`Wrote ${rows.length} event previews`);
